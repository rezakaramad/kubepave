# -----------------------------------------------------------------------------
# Argo CD workload cluster credentials (pull model)
# Creates an argocd-manager ServiceAccount with a long-lived token in each
# workload cluster and stores server + token in Vault. The argocd chart's
# clusters-credential ExternalSecret then materialises the ArgoCD cluster
# Secret so ArgoCD can connect out to the workload cluster.
#
# The ArgoCD cluster name is the kind context name (e.g. "kind-workload") and
# MUST match clusterCredentials[].name in argocd/values-local.yaml.
# -----------------------------------------------------------------------------
register_clusters_argocd() {
  log "Registering workload clusters with ArgoCD (pull model)..."

  get_kind_tenant_clusters | while read -r cluster; do
    local context name server token node_ip
    context="$(kind_context "$cluster")"
    name="$context"  # ArgoCD cluster name == kind context name

    log "Registering $name..."

    # ServiceAccount + cluster-admin binding for ArgoCD to manage the cluster
    kubectl --context "$context" -n kube-system \
      create serviceaccount argocd-manager \
      --dry-run=client -o yaml | kubectl --context "$context" apply -f -

    kubectl --context "$context" \
      create clusterrolebinding argocd-manager \
      --clusterrole=cluster-admin \
      --serviceaccount=kube-system:argocd-manager \
      --dry-run=client -o yaml | kubectl --context "$context" apply -f -

    # Long-lived (legacy) ServiceAccount token — avoids TokenRequest expiry
    kubectl --context "$context" -n kube-system apply -f - <<EOF
apiVersion: v1
kind: Secret
metadata:
  name: argocd-manager-token
  namespace: kube-system
  annotations:
    kubernetes.io/service-account.name: argocd-manager
type: kubernetes.io/service-account-token
EOF

    # Wait for the token to be populated
    for _ in $(seq 1 15); do
      kubectl --context "$context" -n kube-system \
        get secret argocd-manager-token \
        -o jsonpath='{.data.token}' 2>/dev/null | grep -q . && break
      sleep 1
    done

    token=$(kubectl --context "$context" -n kube-system \
      get secret argocd-manager-token \
      -o jsonpath='{.data.token}' | base64 -d)

    # API server reachable from management pods via the kind Docker bridge
    node_ip=$(kubectl --context "$context" get node \
      -o jsonpath='{.items[0].status.addresses[?(@.type=="InternalIP")].address}')
    server="https://${node_ip}:6443"

    log "  server: $server"

    vault_kv_put "local/management/argocd/clusters/${name}" \
      "server" "$server" \
      "token"  "$token"

    ok "$name registered in Vault"
  done
}


# -----------------------------------------------------------------------------
# PowerDNS credentials for external-dns
# Unlike minikube, we do NOT generate new keys here — PowerDNS is already
# running with the values in .powerdns.env. We push those exact values to
# Vault so baseline-management's ExternalSecret can materialise them.
# -----------------------------------------------------------------------------
create_powerdns_secrets() {
  log "Writing PowerDNS credentials to Vault..."

  if [[ ! -f "$SECRETS_FILE" ]]; then
    err "Secrets file not found: $SECRETS_FILE — run ./setup-dns.sh start first"
    return 1
  fi

  # shellcheck source=/dev/null
  source "$SECRETS_FILE"

  vault_kv_put "local/powerdns/db" \
    "user"     "pdns" \
    "password" "$POWERDNS_DB_PASSWORD"

  vault_kv_put "local/powerdns/api" \
    "key" "$POWERDNS_API_KEY"

  ok "PowerDNS credentials written"
}


